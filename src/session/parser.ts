import * as fs from 'fs';
import * as path from 'path';
import * as readline from 'readline';
import { MessageRole, ParsedSession, SessionFileInfo, SessionMessage } from './types';

/*
 * Claude Code session JSONL notes (verified against real files):
 * - Chat records have top-level `type` "user" | "assistant" with `message.role` and `message.content`.
 * - `message.content` is a string or an array of blocks (text / thinking / tool_use / tool_result / image ...).
 * - Assistant output is written one content block per line; lines of one API message share `message.id`.
 * - Tool results are recorded as `type: "user"` with `tool_result` blocks — they are NOT user prompts.
 * - `isMeta`, `isSidechain` (sub-agent), `isCompactSummary` records are not user-visible chat.
 * - Slash commands / local command output are wrapped in `<command-name>`, `<local-command-stdout>` etc.
 * - Many other record types exist (attachment, system, file-history-snapshot, ai-title, summary, ...).
 */

const STRIP_TAGS = [
  'system-reminder',
  'ide_opened_file',
  'ide_selection',
  'ide_diagnostics',
  'command-message',
];

const SKIP_IF_STARTS_WITH = [
  '<local-command-stdout>',
  '<local-command-stderr>',
  '<local-command-caveat>',
  '<bash-stdout>',
  '<bash-stderr>',
  '<task-notification>',
  '<user-prompt-submit-hook>',
  '[Request interrupted by user',
  'Caveat: The messages below were generated by the user while running local commands',
];

function stripTag(text: string, tag: string): string {
  const re = new RegExp(`<${tag}(?:\\s[^>]*)?>[\\s\\S]*?</${tag}>`, 'g');
  return text.replace(re, '');
}

function extractTag(text: string, tag: string): string | undefined {
  const m = new RegExp(`<${tag}>([\\s\\S]*?)</${tag}>`).exec(text);
  return m ? m[1].trim() : undefined;
}

/** Clean a user-typed text, returning '' when it is control metadata rather than a prompt. */
export function cleanUserText(raw: string): string {
  let text = raw;
  for (const tag of STRIP_TAGS) {
    text = stripTag(text, tag);
  }
  text = text.trim();
  if (!text) {
    return '';
  }
  for (const prefix of SKIP_IF_STARTS_WITH) {
    if (text.startsWith(prefix)) {
      return '';
    }
  }
  if (text.startsWith('<command-name>')) {
    // Slash command: keep "/name args" as the user-typed text.
    const name = extractTag(text, 'command-name') ?? '';
    const args = extractTag(text, 'command-args') ?? '';
    return `${name} ${args}`.trim();
  }
  if (text.startsWith('<bash-input>')) {
    const cmd = extractTag(text, 'bash-input');
    return cmd ? `! ${cmd}` : '';
  }
  return text;
}

function textBlocks(content: unknown): string[] {
  if (!Array.isArray(content)) {
    return [];
  }
  const out: string[] = [];
  for (const block of content) {
    if (block && typeof block === 'object' && (block as any).type === 'text' && typeof (block as any).text === 'string') {
      out.push((block as any).text);
    }
  }
  return out;
}

function hasBlockType(content: unknown, type: string): boolean {
  return Array.isArray(content) && content.some((b) => b && typeof b === 'object' && (b as any).type === type);
}

/** Extract the user-typed text from a `type: "user"` record, or '' if it is not a real prompt. */
export function extractUserText(record: any): string {
  if (record.isMeta || record.isSidechain || record.isCompactSummary || record.isVisibleInTranscriptOnly) {
    return '';
  }
  const message = record.message;
  if (!message || (message.role !== undefined && message.role !== 'user')) {
    return '';
  }
  const content = message.content;
  if (typeof content === 'string') {
    return cleanUserText(content);
  }
  if (hasBlockType(content, 'tool_result')) {
    return '';
  }
  return textBlocks(content)
    .map(cleanUserText)
    .filter((t) => t.length > 0)
    .join('\n\n');
}

/** Extract Claude's visible text reply from a `type: "assistant"` record (no thinking / tool_use). */
export function extractAssistantText(record: any): string {
  if (record.isSidechain || record.isApiErrorMessage) {
    return '';
  }
  const message = record.message;
  if (!message || (message.role !== undefined && message.role !== 'assistant')) {
    return '';
  }
  if (message.model === '<synthetic>') {
    return '';
  }
  const content = message.content;
  if (typeof content === 'string') {
    return content.trim();
  }
  return textBlocks(content)
    .map((t) => t.trim())
    .filter((t) => t.length > 0)
    .join('\n\n');
}

function parseTime(value: unknown): { timestamp?: string; time?: number } {
  if (typeof value === 'string' || typeof value === 'number') {
    const t = new Date(value).getTime();
    if (Number.isFinite(t)) {
      return { timestamp: typeof value === 'string' ? value : new Date(t).toISOString(), time: t };
    }
  }
  return {};
}

export function projectNameFrom(cwd: string | undefined, projectDir: string): string {
  if (cwd) {
    const trimmed = cwd.replace(/[\\/]+$/, '');
    const base = trimmed.split(/[\\/]/).pop();
    if (base) {
      return base;
    }
  }
  // Fallback: encoded dir like "-home-user-my-project" -> last segment.
  const parts = projectDir.split('-').filter(Boolean);
  return parts.length ? parts[parts.length - 1] : projectDir || '(unknown)';
}

/** Incremental line-by-line parser for one session file. */
export class SessionParser {
  private messages: SessionMessage[] = [];
  private seenUuids = new Set<string>();
  /** assistant message.id -> logical message, for merging per-block lines. */
  private assistantById = new Map<string, SessionMessage>();
  private sessionId?: string;
  private cwd?: string;
  private aiTitle?: string;
  private summary?: string;
  private invalidLines = 0;

  constructor(private readonly info: SessionFileInfo) {}

  addLine(line: string, lineNo: number): void {
    const trimmed = line.trim();
    if (!trimmed) {
      return;
    }
    let record: any;
    try {
      record = JSON.parse(trimmed);
    } catch {
      this.invalidLines++; // includes a partially written last line
      return;
    }
    if (!record || typeof record !== 'object' || Array.isArray(record)) {
      return;
    }
    try {
      this.handleRecord(record, lineNo);
    } catch {
      // Unexpected shape — skip the record.
    }
  }

  private handleRecord(record: any, lineNo: number): void {
    if (!this.sessionId && typeof record.sessionId === 'string') {
      this.sessionId = record.sessionId;
    }
    if (!this.cwd && typeof record.cwd === 'string' && record.cwd) {
      this.cwd = record.cwd;
    }
    switch (record.type) {
      case 'ai-title':
        if (typeof record.aiTitle === 'string' && record.aiTitle.trim()) {
          this.aiTitle = record.aiTitle.trim();
        }
        return;
      case 'summary':
        if (!this.summary && typeof record.summary === 'string' && record.summary.trim()) {
          this.summary = record.summary.trim();
        }
        return;
      case 'user':
      case 'assistant':
        break;
      default:
        return;
    }

    const uuid = typeof record.uuid === 'string' ? record.uuid : undefined;
    if (uuid) {
      if (this.seenUuids.has(uuid)) {
        return;
      }
      this.seenUuids.add(uuid);
    }

    const role: MessageRole = record.type;
    const text = role === 'user' ? extractUserText(record) : extractAssistantText(record);
    if (!text) {
      return;
    }

    if (role === 'assistant') {
      const apiId = typeof record.message?.id === 'string' ? record.message.id : undefined;
      if (apiId) {
        const existing = this.assistantById.get(apiId);
        if (existing) {
          if (!existing.text.includes(text)) {
            existing.text = `${existing.text}\n\n${text}`;
            existing.lower = existing.text.toLowerCase();
          }
          return;
        }
      }
      const msg = this.push(role, text, uuid, record.timestamp, lineNo);
      if (apiId) {
        this.assistantById.set(apiId, msg);
      }
      return;
    }

    // Guard against the same prompt being logged twice in a row without distinct uuids.
    const prev = this.messages[this.messages.length - 1];
    if (!uuid && prev && prev.role === 'user' && prev.text === text) {
      return;
    }
    this.push(role, text, uuid, record.timestamp, lineNo);
  }

  private push(role: MessageRole, text: string, uuid: string | undefined, ts: unknown, line: number): SessionMessage {
    const msg: SessionMessage = {
      key: uuid ?? `L${line}`,
      uuid,
      role,
      text,
      lower: text.toLowerCase(),
      ...parseTime(ts),
      line,
      index: this.messages.length,
    };
    this.messages.push(msg);
    return msg;
  }

  finish(): ParsedSession {
    const times = this.messages.map((m) => m.time).filter((t): t is number => t !== undefined);
    const firstUser = this.messages.find((m) => m.role === 'user');
    const fallbackTitle = firstUser ? firstUser.text.split('\n')[0].slice(0, 80) : undefined;
    return {
      filePath: this.info.filePath,
      sessionId: this.sessionId ?? path.basename(this.info.filePath, path.extname(this.info.filePath)),
      projectDir: this.info.projectDir,
      projectName: projectNameFrom(this.cwd, this.info.projectDir),
      cwd: this.cwd,
      title: this.aiTitle ?? this.summary ?? fallbackTitle,
      startTime: times.length ? Math.min(...times) : undefined,
      endTime: times.length ? Math.max(...times) : undefined,
      messages: this.messages,
      mtimeMs: this.info.mtimeMs,
      size: this.info.size,
      invalidLines: this.invalidLines,
    };
  }
}

/** Parse JSONL content held in memory (used by tests and small inputs). */
export function parseSessionContent(content: string, info: SessionFileInfo): ParsedSession {
  const parser = new SessionParser(info);
  const lines = content.split(/\r?\n/);
  for (let i = 0; i < lines.length; i++) {
    parser.addLine(lines[i], i + 1);
  }
  return parser.finish();
}

/** Stream-parse a session file. Rejects only if the file cannot be opened/read. */
export async function parseSessionFile(info: SessionFileInfo): Promise<ParsedSession> {
  const parser = new SessionParser(info);
  // Open first so missing / permission-denied files reject cleanly.
  const handle = await fs.promises.open(info.filePath, 'r');
  const stream = handle.createReadStream({ encoding: 'utf8' });
  await new Promise<void>((resolve, reject) => {
    const rl = readline.createInterface({ input: stream, crlfDelay: Infinity });
    let lineNo = 0;
    let failed = false;
    rl.on('line', (line) => {
      lineNo++;
      parser.addLine(line, lineNo);
    });
    rl.on('close', () => {
      if (!failed) {
        resolve();
      }
    });
    stream.on('error', (err) => {
      failed = true;
      rl.close();
      reject(err);
    });
  }).finally(() => {
    stream.destroy();
    handle.close().catch(() => undefined);
  });
  return parser.finish();
}
